# A temporal quality capture must publish the temporal composition, not one of
# the spatial-control branches. The repository checkout currently uses
# base_only for spatial sweeps, so accepting that default here would produce a
# valid-looking capture whose pixels cannot respond to motion or history. Fail
# before launching the player and require the caller to select current,
# learned_only, direct_blend, or another temporal composition explicitly.
validate_temporal_quality_config() {
    local config_path="$1"
python3 - "$config_path" <<'PY'
import json
import os
import sys

path = sys.argv[1]
try:
    with open(path, encoding="utf-8") as handle:
        document = json.load(handle)
except (OSError, json.JSONDecodeError) as error:
    print(f"temporal quality config cannot be read: {path}: {error}", file=sys.stderr)
    raise SystemExit(2)

try:
    quality_lab = document["qualityLab"]
    mode = quality_lab.get("composition", {}).get("mode")
except (KeyError, TypeError, AttributeError):
    print(f"temporal quality config has no qualityLab composition mode: {path}", file=sys.stderr)
    raise SystemExit(2)

if mode is None:
    if not (quality_lab.get("enabled") is False and os.environ.get("TFORGE_ALLOW_SPATIAL_TEMPORAL_CONTROL") == "1"):
        print(f"temporal quality config has no qualityLab composition mode: {path}", file=sys.stderr)
        raise SystemExit(2)
    # The M6 current control deliberately disables Quality Lab and exercises
    # the native current path. Its temporal use is explicit and recorded by
    # the same opt-in that permits base-only regression controls.
    mode = "current"

if mode == "base_only" and os.environ.get("TFORGE_ALLOW_SPATIAL_TEMPORAL_CONTROL") != "1":
    print(
        "temporal capture requires a temporal composition unless "
        "TFORGE_ALLOW_SPATIAL_TEMPORAL_CONTROL=1 is explicitly set; "
        f"base_only is spatial-only: {path}",
        file=sys.stderr,
    )
    raise SystemExit(2)
PY
}
validate_temporal_quality_config "$benchmark_quality_lab_config"

# Keep failure diagnostics opt-in. The ordinary successful path still removes
# the temporary directory, while an explicitly requested failure directory
# receives a best-effort copy before cleanup. This is intentionally a copy of
# the whole temporary tree: it preserves partial PPMs, per-frame motion
# records, the player log, generated reference PPMs, intermediate videos/logs,
# and any other artifacts that exist at the point of failure.
copy_failure_file() {
    local source="$1"
    [[ -n "$source" && -e "$source" ]] || return 0
    if ! cp -a "$source" "$failure_artifact_dir/"; then
        printf 'could not preserve failure artifact: %s\n' "$source" >&2
    fi
}

cleanup_temporal_tmpdir() {
    local exit_status=$?
    if (( exit_status != 0 )) && [[ -n "$failure_artifact_dir" ]]; then
        if mkdir -p "$failure_artifact_dir"; then
            if [[ -d "$tmpdir" ]]; then
                if ! cp -a "$tmpdir"/. "$failure_artifact_dir/"; then
                    printf 'could not preserve temporal failure artifacts from %s\n' "$tmpdir" >&2
                fi
            fi
            # Preserve the captured sequence at a stable, caller-visible path
            # even when the temporary-tree copy is incomplete or interrupted.
            if [[ -d "$sequence_dir" ]]; then
                mkdir -p "$failure_artifact_dir/fsr"
                if ! cp -a "$sequence_dir"/. "$failure_artifact_dir/fsr/"; then
                    printf 'could not preserve captured sequence: %s\n' "$sequence_dir" >&2
                fi
            fi
            # These outputs are caller-selected paths rather than children of
            # tmpdir. Preserve them too when a failed enhanced run wrote them
            # partially before validation rejected the capture.
            copy_failure_file "$output"
            copy_failure_file "$temporal_motion_json"
            copy_failure_file "$temporal_metrics_output"
            copy_failure_file "$temporal_events_json"
            copy_failure_file "$temporal_static_mask_json"
            printf 'preserved temporal failure artifacts: %s\n' "$failure_artifact_dir" >&2
        else
            printf 'could not create temporal failure artifact directory: %s\n' "$failure_artifact_dir" >&2
        fi
    fi
    rm -rf "$tmpdir"
    rm -rf "$benchmark_config_home"
    exit "$exit_status"
}
