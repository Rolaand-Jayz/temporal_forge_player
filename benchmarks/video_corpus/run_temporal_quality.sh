reject_existing_output() {
    local path="$1"
    [[ -z "$path" || ( ! -e "$path" && ! -L "$path" ) ]] || {
        printf 'requested sidecar already exists: %s\n' "$path" >&2
        exit 2
    }
}

# Enhanced captures are provenance-bearing outputs. Reusing an existing
# sidecar can make a fresh frame sequence appear to have motion/event evidence
# that was generated by a different binary, input, or configuration. The
# caller must provide a new namespace for every capture.
reject_existing_output "$temporal_motion_json"
reject_existing_output "$temporal_metrics_output"
reject_existing_output "$temporal_events_json"

if [[ -n "$temporal_motion_json" ]]; then
    temporal_motion_export=1
fi
if [[ -n "$temporal_events_json" ]]; then
    temporal_event_trace_export=1
fi
[[ -x "$player" && -s "$input" && -s "$reference" ]] || {
    printf 'player, input, and reference must exist\n' >&2
    exit 1
}
[[ "$frames" =~ ^[1-9][0-9]*$ ]] || {
    printf 'frames must be a positive integer\n' >&2
    exit 2
}
[[ "$temporal_warmup_frames" =~ ^[0-9]+$ ]] || {
    printf 'TFORGE_TEMPORAL_WARMUP_FRAMES must be a non-negative integer\n' >&2
    exit 2
}
