# The decode thread can complete one additional sidecar write between the
# moment the requested PPM sequence becomes complete and the runner stops the
# player.  Keep only records that correspond to the scored image sequence;
# otherwise the strict assemblers correctly reject the capture as ambiguous.
prune_extra_diagnostic_records() {
    local prefix="$1"
    local path name index
    for path in "$sequence_dir"/${prefix}_*.json; do
        [[ -e "$path" ]] || continue
        name="${path##*/}"
        index="${name#${prefix}_}"
        index="${index%.json}"
        [[ "$index" =~ ^[0-9]+$ ]] || continue
        if (( 10#$index >= frames )); then
            rm -f -- "$path"
        fi
    done
}

