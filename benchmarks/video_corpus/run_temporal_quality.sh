# The legacy CSV above intentionally keeps its original frame-delta schema.
# When a real motion sidecar is supplied, measure_temporal_sequence.py gets a
# matched PPM reference sequence and writes a separate per-class CSV containing
# the defined flicker/edge/motion/ghost/reset fields. No identity motion or
# guessed event metadata is inserted by this bridge.
if [[ -n "$temporal_motion_json$temporal_metrics_output$temporal_class" ]]; then
    [[ -n "$temporal_motion_json" && -f "$temporal_motion_json" ]] || {
        printf 'TFORGE_TEMPORAL_MOTION_JSON must name an existing JSON sidecar\n' >&2
        exit 1
    }
    [[ -n "$temporal_metrics_output" && -n "$temporal_class" ]] || {
        printf 'temporal metrics require TFORGE_TEMPORAL_METRICS_CSV and '
        printf 'TFORGE_TEMPORAL_CLASS\n' >&2
        exit 1
    }
    [[ -n "$temporal_candidate_id" && -n "$temporal_scene" && \
       -n "$temporal_config_id" && "$temporal_start_frame" =~ ^[0-9]+$ ]] || {
        printf 'temporal metrics require candidate, scene, config, and non-negative start-frame identity\n' >&2
        exit 1
    }
    [[ -n "$temporal_static_mask_json" && -f "$temporal_static_mask_json" ]] || {
        printf 'temporal metrics require an existing TFORGE_TEMPORAL_STATIC_MASK_JSON sidecar\n' >&2
        exit 1
    }
    temporal_reference_dir="$tmpdir/reference_ppm"
    mkdir -p "$temporal_reference_dir"
    run_ffmpeg -hide_banner -loglevel error -i "$reference" -frames:v "$frames" \
        -vf "scale=${output_width}:${output_height}:flags=lanczos,format=rgb24,setsar=1" \
        -start_number 0 \
        "$temporal_reference_dir/reference_%04d.ppm"

    temporal_command=(
        python3
        "$runner_dir/../../tools/measure_temporal_sequence.py"
        --class "$temporal_class"
        --candidate-id "$temporal_candidate_id"
        --scene "$temporal_scene"
        --config-id "$temporal_config_id"
        --start-frame "$temporal_start_frame"
        --candidate-dir "$sequence_dir"
        --reference-dir "$temporal_reference_dir"
        --motion-json "$temporal_motion_json"
        --static-mask-json "$temporal_static_mask_json"
