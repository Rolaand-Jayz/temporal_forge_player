# Copy a caller-selected enhanced artifact unless it is already the exact
# destination. The sidecar paths are allowed to live inside artifact_dir; a
# plain `cp source artifact_dir/` treats that valid no-op as an error and can
# turn a successful metric run into a false failure. Real copy errors still
# propagate through set -e.
copy_artifact_file() {
    local source="$1"
    local destination_dir="$2"
    local destination="$destination_dir/$(basename "$source")"
    if [[ "$(realpath "$source")" == "$(realpath -m "$destination")" ]]; then
        return 0
    fi
    cp "$source" "$destination_dir/"
}

