    pipelines = &nativeInt8UltraPipelines1080_;
    available = &nativeInt8UltraPipelines1080Available_;
    break;
  case NativeInt8Graph::UltraPerformance2160:
    name = "ultraperf_2160";
    pipelines = &nativeInt8UltraPipelines2160_;
    available = &nativeInt8UltraPipelines2160Available_;
    break;
  case NativeInt8Graph::Performance2160:
    name = "performance_2160";
    pipelines = &nativeInt8PerformancePipelines2160_;
    available = &nativeInt8PerformancePipelines2160Available_;
    break;
  case NativeInt8Graph::Performance4320:
    name = "performance_4320";
    pipelines = &nativeInt8PerformancePipelines4320_;
    available = &nativeInt8PerformancePipelines4320Available_;
    break;
  case NativeInt8Graph::QualityFourThree1440:
    name = "quality_4x3_1440";
    pipelines = &nativeInt8QualityFourThreePipelines1440_;
    available = &nativeInt8QualityFourThreePipelines1440Available_;
