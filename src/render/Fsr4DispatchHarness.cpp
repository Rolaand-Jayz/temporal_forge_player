bool Fsr4DispatchHarness::downscaleRgb10(
    VkImage sourceImage, VkImageView sourceView, uint32_t sourceWidth,
    uint32_t sourceHeight, VkImage destinationImage,
    VkImageView destinationView, uint32_t destinationWidth,
    uint32_t destinationHeight) {
  if (!sourceImage || !sourceView || !destinationImage || !destinationView ||
      !downscalePipeline_ || !cmd_ || !fence_ || sourceWidth == 0 ||
      sourceHeight == 0 || destinationWidth == 0 || destinationHeight == 0)
    return false;
  vkResetCommandBuffer(cmd_, 0);
  VkCommandBufferBeginInfo begin{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
  if (vkBeginCommandBuffer(cmd_, &begin) != VK_SUCCESS) return false;
  VkImageMemoryBarrier barriers[2]{};
  for (auto &barrier : barriers) {
    barrier.sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
    barrier.oldLayout = VK_IMAGE_LAYOUT_GENERAL;
    barrier.newLayout = VK_IMAGE_LAYOUT_GENERAL;
    barrier.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    barrier.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    barrier.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
  }
  barriers[0].srcAccessMask = VK_ACCESS_SHADER_WRITE_BIT;
  barriers[0].dstAccessMask = VK_ACCESS_SHADER_READ_BIT;
  barriers[0].image = sourceImage;
  barriers[1].srcAccessMask = VK_ACCESS_SHADER_READ_BIT | VK_ACCESS_SHADER_WRITE_BIT;
  barriers[1].dstAccessMask = VK_ACCESS_SHADER_WRITE_BIT;
  barriers[1].image = destinationImage;
  vkCmdPipelineBarrier(cmd_, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT,
                       VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT, 0, 0, nullptr, 0,
                       nullptr, 2, barriers);
  VkDescriptorSetAllocateInfo ai{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
  ai.descriptorPool = descPool_;
  ai.descriptorSetCount = 1;
  ai.pSetLayouts = &downscaleDescLayout_;
  VkDescriptorSet set = VK_NULL_HANDLE;
  if (vkAllocateDescriptorSets(device_, &ai, &set) != VK_SUCCESS) {
    vkEndCommandBuffer(cmd_);
    return false;
  }
  VkDescriptorImageInfo srcInfo{VK_NULL_HANDLE, sourceView, VK_IMAGE_LAYOUT_GENERAL};
  VkDescriptorImageInfo dstInfo{VK_NULL_HANDLE, destinationView, VK_IMAGE_LAYOUT_GENERAL};
  VkWriteDescriptorSet writes[2]{};
  writes[0] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, nullptr, set, 0, 0, 1,
               VK_DESCRIPTOR_TYPE_STORAGE_IMAGE, &srcInfo, nullptr, nullptr};
  writes[1] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, nullptr, set, 1, 0, 1,
               VK_DESCRIPTOR_TYPE_STORAGE_IMAGE, &dstInfo, nullptr, nullptr};
  vkUpdateDescriptorSets(device_, 2, writes, 0, nullptr);
  const uint32_t push[4] = {sourceWidth, sourceHeight, destinationWidth,
                            destinationHeight};
  vkCmdBindPipeline(cmd_, VK_PIPELINE_BIND_POINT_COMPUTE, downscalePipeline_);
  vkCmdBindDescriptorSets(cmd_, VK_PIPELINE_BIND_POINT_COMPUTE,
                          downscaleLayout_, 0, 1, &set, 0, nullptr);
  vkCmdPushConstants(cmd_, downscaleLayout_, VK_SHADER_STAGE_COMPUTE_BIT, 0,
                     sizeof(push), push);
  vkCmdDispatch(cmd_, (destinationWidth + 15u) / 16u,
                (destinationHeight + 15u) / 16u, 1);
  if (vkEndCommandBuffer(cmd_) != VK_SUCCESS) return false;
  VkSubmitInfo submit{VK_STRUCTURE_TYPE_SUBMIT_INFO};
  submit.commandBufferCount = 1;
  submit.pCommandBuffers = &cmd_;
  if (vkQueueSubmit(queue_, 1, &submit, fence_) != VK_SUCCESS)
    return false;
  // Serialize the handoff before the next harness binds the destination as
  // an input. dispatchFrame() leaves this shared fence reset after its own
  // wait, so waiting here must be for the downscale submission itself.
  if (vkWaitForFences(device_, 1, &fence_, VK_TRUE, UINT64_MAX) != VK_SUCCESS)
    return false;
  vkResetFences(device_, 1, &fence_);
  vkResetCommandBuffer(cmd_, 0);
  vkFreeDescriptorSets(device_, descPool_, 1, &set);
  return true;
}

bool Fsr4DispatchHarness::createNativeInt8Pipelines() {
  std::array<VkDescriptorSetLayoutBinding, 4> bindings{};
  for (uint32_t i = 0; i < bindings.size(); ++i)
    bindings[i] = {i, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1,
                   VK_SHADER_STAGE_COMPUTE_BIT, nullptr};
  VkDescriptorSetLayoutCreateInfo descriptorInfo{};
  descriptorInfo.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
  descriptorInfo.bindingCount = static_cast<uint32_t>(bindings.size());
  descriptorInfo.pBindings = bindings.data();
  if (vkCreateDescriptorSetLayout(device_, &descriptorInfo, nullptr,
                                  &nativeInt8DescLayout_) != VK_SUCCESS)
    return false;

  VkPipelineLayoutCreateInfo layoutInfo{};
  layoutInfo.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
  layoutInfo.setLayoutCount = 1;
  layoutInfo.pSetLayouts = &nativeInt8DescLayout_;
  if (vkCreatePipelineLayout(device_, &layoutInfo, nullptr,
                             &nativeInt8Layout_) != VK_SUCCESS)
    return false;

  std::vector<uint8_t> cacheData;
  std::filesystem::path cachePath;
  if (const char *xdgCache = std::getenv("XDG_CACHE_HOME"))
    cachePath = std::filesystem::path(xdgCache) /
                "temporal-forge-player/native-int8.bin";
  else if (const char *home = std::getenv("HOME"))
    cachePath = std::filesystem::path(home) /
                ".cache/temporal-forge-player/native-int8.bin";
  if (!cachePath.empty()) {
    std::ifstream cacheFile(cachePath, std::ios::binary | std::ios::ate);
    if (cacheFile && cacheFile.tellg() > 0 && cacheFile.tellg() <= (64 << 20)) {
      cacheData.resize(static_cast<size_t>(cacheFile.tellg()));
      cacheFile.seekg(0);
      cacheFile.read(reinterpret_cast<char *>(cacheData.data()),
                     static_cast<std::streamsize>(cacheData.size()));
      if (!cacheFile)
        cacheData.clear();
    }
  }
  VkPipelineCacheCreateInfo cacheInfo{};
  cacheInfo.sType = VK_STRUCTURE_TYPE_PIPELINE_CACHE_CREATE_INFO;
  cacheInfo.initialDataSize = cacheData.size();
  cacheInfo.pInitialData = cacheData.empty() ? nullptr : cacheData.data();
  if (vkCreatePipelineCache(device_, &cacheInfo, nullptr,
                            &nativeInt8PipelineCache_) != VK_SUCCESS) {
    cacheInfo.initialDataSize = 0;
    cacheInfo.pInitialData = nullptr;
    if (vkCreatePipelineCache(device_, &cacheInfo, nullptr,
                              &nativeInt8PipelineCache_) != VK_SUCCESS)
      return false;
  }
  logInfo("Fsr4Harness: native INT8 pipeline cache loaded ({} bytes)",
          cacheData.size());
  return true;
}

