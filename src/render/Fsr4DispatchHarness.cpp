      if (bestFindingsTemporal ||
          std::getenv("TFORGE_FSR4_CURRENT_BLEND_LINEAR"))
        pp.slot0[2] |= 16u;
      if (std::getenv("TFORGE_FSR4_CURRENT_BASE_JITTERED"))
        pp.slot0[2] |= 32u;
