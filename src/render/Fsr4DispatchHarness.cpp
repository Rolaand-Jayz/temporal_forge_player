      // unjittered spatial base as base_only.  This isolates learned/detail
      // changes from a deliberate phase shift without changing current mode.
      if (std::getenv("TFORGE_FSR4_EXPERIMENTAL_BASE_UNJITTERED"))
        pp.slot0[2] |= 128u;
