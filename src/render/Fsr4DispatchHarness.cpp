bool Fsr4DispatchHarness::createGpuBuffer(VkDeviceSize size,
                                          VkBufferUsageFlags usage,
                                          VkMemoryPropertyFlags memProps,
                                          VkBuffer &buf, VkDeviceMemory &mem,
                                          const char *tag) {
  VkBufferCreateInfo bci{};
  bci.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
  bci.size = size;
  bci.usage = usage;
  bci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
  if (vkCreateBuffer(device_, &bci, nullptr, &buf) != VK_SUCCESS) {
    logError("Fsr4Harness: createBuffer '{}' failed", tag);
    return false;
  }
  VkMemoryRequirements mr{};
  vkGetBufferMemoryRequirements(device_, buf, &mr);
  uint32_t memType = findMemoryTypeFor(physical_, mr.memoryTypeBits, memProps);
  if (memType == ~0u) {
    logError("Fsr4Harness: no memory type for '{}'", tag);
    vkDestroyBuffer(device_, buf, nullptr);
    buf = VK_NULL_HANDLE;
    return false;
  }
  VkMemoryAllocateInfo mai{};
  mai.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
  mai.allocationSize = mr.size;
  mai.memoryTypeIndex = memType;
  if (vkAllocateMemory(device_, &mai, nullptr, &mem) != VK_SUCCESS) {
    logError("Fsr4Harness: allocateMemory '{}' failed", tag);
    vkDestroyBuffer(device_, buf, nullptr);
    buf = VK_NULL_HANDLE;
    return false;
  }
  vkBindBufferMemory(device_, buf, mem, 0);
  return true;
}

void Fsr4DispatchHarness::freeGpuBuffer(VkBuffer &buf, VkDeviceMemory &mem) {
  if (device_ == VK_NULL_HANDLE)
    return;
  if (buf != VK_NULL_HANDLE) {
    vkDestroyBuffer(device_, buf, nullptr);
    buf = VK_NULL_HANDLE;
  }
  if (mem != VK_NULL_HANDLE) {
    vkFreeMemory(device_, mem, nullptr);
    mem = VK_NULL_HANDLE;
  }
}

