    vkDestroyPipeline(device_, residualAddPipeline_, nullptr);
  if (convDwPipeline_)
    vkDestroyPipeline(device_, convDwPipeline_, nullptr);
  if (convLayout_)
    vkDestroyPipelineLayout(device_, convLayout_, nullptr);
  if (prepassPipeline_)
    vkDestroyPipeline(device_, prepassPipeline_, nullptr);
  if (prepassLayout_)
    vkDestroyPipelineLayout(device_, prepassLayout_, nullptr);
  if (downscalePipeline_)
    vkDestroyPipeline(device_, downscalePipeline_, nullptr);
  if (downscaleLayout_)
    vkDestroyPipelineLayout(device_, downscaleLayout_, nullptr);
  for (auto *pack :
       {&nativeInt8QualityPipelines1080_, &nativeInt8QualityPipelines2160_,
        &nativeInt8UltraPipelines1080_, &nativeInt8UltraPipelines2160_,
       &nativeInt8PerformancePipelines2160_,
        &nativeInt8PerformancePipelines4320_,
        &nativeInt8QualityFourThreePipelines1440_,
        &nativeInt8UltraFourThreePipelines1440_,
        &nativeInt8PerformanceFourThreePipelines1440_,
        &nativeInt8QualityFourThreePipelines2880_,
        &nativeInt8UltraFourThreePipelines2880_,
        &nativeInt8PerformanceFourThreePipelines2880_})
    for (auto &pipeline : *pack) {
      if (pipeline)
        vkDestroyPipeline(device_, pipeline, nullptr);
      pipeline = VK_NULL_HANDLE;
    }
  if (nativeInt8DescPool_)
    vkDestroyDescriptorPool(device_, nativeInt8DescPool_, nullptr);
  if (nativeInt8Layout_)
    vkDestroyPipelineLayout(device_, nativeInt8Layout_, nullptr);
  persistGenericPipelineCache();
  if (genericPipelineCache_)
    vkDestroyPipelineCache(device_, genericPipelineCache_, nullptr);
  if (nativeInt8PipelineCache_)
    vkDestroyPipelineCache(device_, nativeInt8PipelineCache_, nullptr);
  if (nativeInt8DescLayout_)
    vkDestroyDescriptorSetLayout(device_, nativeInt8DescLayout_, nullptr);
  if (descPool_)
    vkDestroyDescriptorPool(device_, descPool_, nullptr);
  if (descLayout_)
    vkDestroyDescriptorSetLayout(device_, descLayout_, nullptr);
  if (convDescLayout_)
    vkDestroyDescriptorSetLayout(device_, convDescLayout_, nullptr);
  if (postpassDescLayout_)
    vkDestroyDescriptorSetLayout(device_, postpassDescLayout_, nullptr);
